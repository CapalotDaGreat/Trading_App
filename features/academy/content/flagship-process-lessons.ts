function mcq(
  id: string,
  prompt: string,
  choices: string[],
  correctIndex: number,
  choiceExplanations: string[],
  conceptId: string,
): Lesson['quiz'][number] {
  return {
    id,
    prompt,
    choices,
    correctIndex,
    explanation: choiceExplanations[correctIndex] ?? '',
    choiceExplanations,
    conceptId,
  };
}

